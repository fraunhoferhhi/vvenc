"""Join genuine PPO policy transitions, VVC AU bits and frozen YOLO detections.

Inputs are per-episode files. Detections MUST be generated by the same frozen
YOLOv5n and preprocessing/confidence/NMS protocol used in the locked Baseline.

Detection JSONL schema: one record for EVERY frame, including empty frames:
{"video_id":"video_01","poc":0,"detections":[{"x1":10,"y1":10,"x2":40,"y2":40,"confidence":0.91,"class_id":2}]}

Source and decoded detections MUST have the same video_id and POC set,
coordinates, and underlying frame dimensions. An empty detection list is not
equivalent to a missing frame. Class id 2 is COCO 'car'.

The returned PPO transition list is in POLICY DECISION ORDER (observation
file order); rate accumulation for the RL reward is in POLICY DECISION ORDER, using
true per-POC AU bits. Output AU order is audited separately; neither
order may be assumed to be increasing POC. No learning occurs here.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
import json
import math
from pathlib import Path
from typing import Any

from au_rate_audit import read_au_bits
from reward_metrics import Detection, calculate_frame_reward


def _jsonl(path: Path):
    if not path.is_file():
        raise FileNotFoundError(str(path))
    with path.open(encoding="utf-8") as stream:
        rows = []
        for linenum, line in enumerate(stream, start=1):
            if not line.strip():
                continue
            try:
                data = json.loads(line)
            except json.JSONDecodeError as err:
                raise ValueError(str(path) + ":" + str(linenum) + ": invalid JSON") from err
            if not isinstance(data, dict):
                raise ValueError(str(path) + ":" + str(linenum) + ": expected JSON object")
            rows.append(data)
    return rows


def read_detections(path: Path, video_id: str, expected_pocs: set[int]):
    result = {}
    for record in _jsonl(path):
        if record.get("video_id") != video_id:
            raise ValueError("Detection video_id mismatch in " + str(path))
        poc = record.get("poc")
        if type(poc) is not int or poc not in expected_pocs or poc in result:
            raise ValueError("Duplicate/unexpected detection POC in " + str(path))
        boxes = record.get("detections")
        if not isinstance(boxes, list):
            raise ValueError("Missing detections list at POC " + str(poc))
        converted = []
        for box in boxes:
            if not isinstance(box, dict):
                raise ValueError("Non-object detection")
            if box.get("class_id", 2) != 2:
                raise ValueError("Non-car detection; filter to COCO class_id=2 upstream")
            try:
                converted.append(Detection(
                    x1=float(box["x1"]), y1=float(box["y1"]),
                    x2=float(box["x2"]), y2=float(box["y2"]),
                    confidence=float(box["confidence"]),
                ))
            except (KeyError, ValueError, TypeError) as err:
                raise ValueError("Invalid car detection at POC " + str(poc)) from err
        result[poc] = converted
    if set(result) != expected_pocs:
        raise ValueError("Missing detection POCs in " + str(path)
                         + " expected=" + str(sorted(expected_pocs))
                         + " received=" + str(sorted(result)))
    return result


def join_episode(
    *,
    video_id: str,
    trajectory_file: Path,
    au_csv: Path,
    bitstream: Path,
    source_detections: Path,
    decoded_detections: Path,
    frame_rate: float,
    target_bps: float,
    beta: float,
    iou_threshold: float = 0.5,
    empty_reference_fp_penalty: float = 0.25,
) -> list[dict[str, Any]]:
    if not video_id:
        raise ValueError("video_id must be nonempty")
    trajectory = _jsonl(trajectory_file)
    n = len(trajectory)
    if n < 1:
        raise ValueError("Empty PPO trajectory")
    pocs = []
    for row in trajectory:
        poc = row.get("poc")
        if type(poc) is not int or poc < 0 or poc >= n or poc in pocs:
            raise ValueError("Trajectory has invalid or duplicate POC")
        if row.get("reward") is not None or row.get("done") is not None:
            raise ValueError("Trajectory already includes reward/done; refuse double-join")
        if len(row.get("global", [])) != 8 or len(row.get("spatial", [])) != 3:
            raise ValueError("Malformed PPO state at POC " + str(poc))
        if len(row.get("raw_action") or []) != 12:
            raise ValueError("Missing PPO raw latent action; zero-policy not trainable")
        if len(row.get("discrete_action") or []) != 12:
            raise ValueError("Missing discrete QP map")
        if not all(type(a) is int and -2 <= a <= 2 for a in row["discrete_action"]):
            raise ValueError("Invalid QP action")
        if not isinstance(row.get("value"), (int, float)) or not math.isfinite(row["value"]):
            raise ValueError("Non-finite PPO value")
        if not isinstance(row.get("log_prob"), (int, float)) or not math.isfinite(row["log_prob"]):
            raise ValueError("Non-finite PPO log_prob")
        pocs.append(poc)

    expected = set(range(n))
    if set(pocs) != expected:
        raise ValueError("Missing trajectory POCs")

    source = read_detections(source_detections, video_id, expected)
    decoded = read_detections(decoded_detections, video_id, expected)
    output_aus = read_au_bits(au_csv, bitstream, n)

    # Each reward belongs to a POLICY DECISION, not to the VVC output
    # scheduler. Accumulate exact emitted AU bits by the SAME order in which
    # observations/actions were sampled and in which GAE will be computed.
    # AU output_step is retained separately for auditing reorder; it must
    # not silently replace policy step in the bitrate penalty clock.
    au_by_poc = {au.poc: au for au in output_aus}
    policy_bits = 0
    joined = []
    for index, row in enumerate(trajectory):
        poc = row["poc"]
        au = au_by_poc[poc]
        policy_bits += au.au_bits
        reward = calculate_frame_reward(
            video_id=video_id,
            poc=poc,
            encoded_step=index + 1,
            pseudo_gt=source[poc],
            reconstructed=decoded[poc],
            actual_frame_bits=au.au_bits,
            cumulative_bits=policy_bits,
            frame_rate=frame_rate,
            target_bps=target_bps,
            beta=beta,
            iou_threshold=iou_threshold,
            empty_reference_fp_penalty=empty_reference_fp_penalty,
        )
        next_value = float(trajectory[index + 1]["value"]) if index + 1 < n else 0.0
        result = dict(row)
        result["video_id"] = video_id
        result["reward"] = reward.reward
        result["done"] = (index == n - 1)
        result["next_value"] = next_value
        result["reward_diagnostics"] = asdict(reward)
        result["policy_decision_step"] = index + 1
        result["au_output_step"] = au.output_step
        joined.append(result)

    assert len(joined) == n and set(x["poc"] for x in joined) == expected
    return joined


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--video-id", required=True)
    p.add_argument("--trajectory", type=Path, required=True)
    p.add_argument("--au-csv", type=Path, required=True)
    p.add_argument("--bitstream", type=Path, required=True)
    p.add_argument("--source-detections", type=Path, required=True)
    p.add_argument("--decoded-detections", type=Path, required=True)
    p.add_argument("--frame-rate", type=float, required=True)
    p.add_argument("--target-bps", type=float, required=True)
    p.add_argument("--beta", type=float, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--iou-threshold", type=float, default=0.5)
    a = p.parse_args()
    joined = join_episode(
        video_id=a.video_id,
        trajectory_file=a.trajectory,
        au_csv=a.au_csv,
        bitstream=a.bitstream,
        source_detections=a.source_detections,
        decoded_detections=a.decoded_detections,
        frame_rate=a.frame_rate,
        target_bps=a.target_bps,
        beta=a.beta,
        iou_threshold=a.iou_threshold,
    )
    if a.output.exists():
        p.error("Refusing to overwrite existing joined rollout: " + str(a.output))
    a.output.parent.mkdir(parents=True, exist_ok=True)
    with a.output.open("w", encoding="utf-8") as f:
        for row in joined:
            f.write(json.dumps(row, allow_nan=False, separators=(",", ":")) + "\n")
    print("JOIN_PASS video_id=" + a.video_id + " transitions=" + str(len(joined))
          + " total_reward=" + str(round(sum(r["reward"] for r in joined), 4)))
    print("Warning: YOLO outputs and exact Baseline evaluator MUST be validated separately.")


if __name__ == "__main__":
    main()
